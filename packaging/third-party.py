def standard_texts():
    """MIT and Apache-2.0 from our own licence files, and the Boost licence."""
    with open(os.path.join(ROOT, "LICENSE-MIT"), encoding="utf-8") as fh:
        mit = re.sub(r"(?m)^Copyright .*$", "Copyright (c) the crate's authors", fh.read().strip())
    with open(os.path.join(ROOT, "LICENSE-APACHE"), encoding="utf-8") as fh:
        apache = fh.read().strip()
    return [("MIT", mit), ("Apache-2.0", apache), ("BSL-1.0", BSL)]


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "THIRD-PARTY-LICENSES.md")
    pkgs = {}
    for app, t in ((a, t) for a, ts in APPS for t in ts):
        meta = metadata(t)
        by_id = {p["id"]: p for p in meta["packages"]}
        for pid in linked(meta, app):
            p = by_id[pid]
            if p["source"] is not None:  # our own workspace crates have no source
                pkgs[(p["name"], p["version"])] = p
    rows = sorted(pkgs.values(), key=lambda p: (p["name"].lower(), p["version"]))

    texts = {}  # licence text -> crates that ship it
    missing = []
    for p in rows:
        found = licence_texts(p)
        if not found:
            missing.append(p)
        for _, text in found:
            texts.setdefault(text, []).append(f'{p["name"]} {p["version"]}')

    lines = [
        "# Third-party licences",
        "",
        "Generated by `packaging/third-party.py` from `cargo metadata`; do not edit by hand.",
        "See THIRD-PARTY.md for the notices that are not Rust crates (Slint, fonts, OCR models,",
        "Adobe CMaps, hyphenation patterns, spelling dictionaries).",
        "",
        f"{len(rows)} crates are linked into the desktop app on Linux, Windows or macOS.",
        "",
        "| Crate | Version | Licence | Source |",
        "|---|---|---|---|",
    ]
    for p in rows:
        lic = (p.get("license") or "see licence file").replace("|", "\\|")
        repo = p.get("repository") or ""
        lines.append(f'| {p["name"]} | {p["version"]} | {lic} | {repo} |')
    if missing:
        lines += [
            "",
            "## Crates without a licence file",
            "",
            "These crates ship no licence text. The standard text of their licence (under "
            "Standard licence texts below) applies, with the copyright held by their authors:",
            "",
        ]
        for p in missing:
            authors = ", ".join(p.get("authors") or []) or "the authors"
            lines.append(f'- {p["name"]} {p["version"]} ({p.get("license")}), {authors}')
    lines += ["", "## Licence texts", ""]
    for text, users in sorted(texts.items(), key=lambda kv: kv[1][0]):
        lines += [f"### Used by: {', '.join(users)}", "", "```text", text, "```", ""]
    if missing:
        lines += ["## Standard licence texts", ""]
        for name, text in standard_texts():
            lines += [f"### {name}", "", "```text", text, "```", ""]
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines).rstrip() + "\n")
    print(f"{out_path}: {len(rows)} crates, {len(texts)} licence texts, {len(missing)} without a file")


if __name__ == "__main__":
    main()
