#!/usr/bin/env python3
"""Writes THIRD-PARTY-LICENSES.md: every crate linked into the desktop app on Linux, Windows
or macOS, or into the mobile app on Android or iOS (normal dependencies only; build and dev dependencies are not distributed), with
its licence and the licence texts the crate ships, deduplicated.

usage: packaging/third-party.py [OUT]   (default: THIRD-PARTY-LICENSES.md at the root)
Reads `cargo metadata`; no network access beyond what cargo itself needs.
"""

import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# (app package, targets it ships on)
APPS = [
    (
        "pagebara-app",
        ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc", "aarch64-apple-darwin", "x86_64-apple-darwin"],
    ),
    ("pagebara-mobile", ["aarch64-linux-android", "aarch64-apple-ios"]),
]
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)", re.I)


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", target],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def linked(meta, app):
    """Package ids reachable from the app through normal dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == app)
    seen, todo = set(), [root]
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return seen


def licence_texts(pkg):
    """(file name, text) for each licence file in the crate's source directory."""
    d = os.path.dirname(pkg["manifest_path"])
    files = []
    if pkg.get("license_file"):
        files.append(pkg["license_file"])
    for name in sorted(os.listdir(d)):
        p = os.path.join(d, name)
        if LICENSE_FILE.match(name) and os.path.isfile(p) and name not in files:
            files.append(name)
        if name in ("LICENSES", "licenses") and os.path.isdir(p):
            files += [os.path.join(name, f) for f in sorted(os.listdir(p))]
    texts = []
    for f in files:
        try:
            with open(os.path.join(d, f), encoding="utf-8", errors="replace") as fh:
                texts.append((os.path.basename(f), fh.read().strip()))
        except OSError:
            pass
    return texts


