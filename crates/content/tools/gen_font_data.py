# Generates crates/content/src/font/data.rs from the Adobe Glyph List, the Core 14 AFMs
# and the Latin encodings of ISO 32000 Annex D.
# Usage: gen_font_data.py <core14 afm dir> <macexpert.py> <out.rs> && rustfmt --edition 2024 <out.rs>
# Needs the aglfn package (/usr/share/aglfn) and pdfminer (latin_enc); <macexpert.py> is
# reportlab's pdfbase/_fontdata_enc_macexpert.py (MacExpertEncoding of Annex D.4 as a tuple).
import ast, sys, re
sys.path.insert(0, '/usr/lib/python3/dist-packages')
from pdfminer.latin_enc import ENCODING

AFM = sys.argv[1].rstrip('/') + '/'
src = open(sys.argv[2]).read()
MAC_EXPERT = ast.literal_eval(src[src.index('(', src.index('MacExpertEncoding')):])
out_path = sys.argv[3]

names = {}
for path in ['/usr/share/aglfn/glyphlist.txt', '/usr/share/aglfn/zapfdingbats.txt']:
    for line in open(path):
        if line.startswith('#') or ';' not in line: continue
        n, cps = line.strip().split(';')[:2]
        cp = int(cps.split()[0], 16)
        assert cp < 0x10000
        names.setdefault(n, cp)

# Expert glyphs (small caps, old style figures, superiors) sit in the Private Use Area in the
# list; for text they read as their plain letters.
for n, cp in list(names.items()):
    if not 0xE000 <= cp <= 0xF8FF: continue
    for suffix in ('small', 'oldstyle', 'superior', 'inferior', 'fitted'):
        if n.endswith(suffix) and len(n) > len(suffix):
            base = n[:-len(suffix)]
            base = base.lower() if suffix == 'small' else base
            if not 0xE000 <= names.get(base, 0xE000) <= 0xF8FF:
                names[n] = names[base]
            break
def afm(name):
    chars, info = [], {}
    for line in open(AFM + name + '.afm', encoding='latin-1'):
        f = line.split()
        if not f: continue
        if f[0] == 'C':
            d = {}
            for part in line.split(';'):
                p = part.split()
                if p: d[p[0]] = p[1:]
            chars.append((int(d['C'][0]), d['N'][0], int(float(d['WX'][0]))))
        elif f[0] in ('Ascender', 'Descender'):
            info[f[0]] = int(float(f[1]))
        elif f[0] == 'FontBBox':
            info['bbox'] = [int(float(x)) for x in f[1:5]]
    return chars, info

fonts = ['Courier', 'Courier-Bold', 'Courier-Oblique', 'Courier-BoldOblique',
         'Helvetica', 'Helvetica-Bold', 'Helvetica-Oblique', 'Helvetica-BoldOblique',
         'Times-Roman', 'Times-Bold', 'Times-Italic', 'Times-BoldItalic', 'Symbol', 'ZapfDingbats']
metrics = {f: afm(f) for f in fonts}
for f in fonts:
    for _, n, _ in metrics[f][0]:
        if n not in names:
            print('afm name not in AGL', f, n, file=sys.stderr)
            names[n] = 0

encs = {k: [None] * 256 for k in ['STANDARD', 'MAC_ROMAN', 'WIN_ANSI', 'PDF_DOC', 'MAC_EXPERT', 'SYMBOL', 'ZAPF_DINGBATS']}
assert len(MAC_EXPERT) == 256
for c, n in enumerate(MAC_EXPERT):
    if n is None: continue
    if n not in names:
        print('expert name not in AGL', n, file=sys.stderr); names[n] = 0
    encs['MAC_EXPERT'][c] = n

for n, s, m, w, p in ENCODING:
    if n not in names:
        print('enc name not in AGL', n, file=sys.stderr); names[n] = 0
    for k, c in (('STANDARD', s), ('MAC_ROMAN', m), ('WIN_ANSI', w), ('PDF_DOC', p)):
        if c is not None: encs[k][c] = n
# Annex D: WinAnsi maps unused codes to bullet, 0xA0 to space and 0xAD to hyphen.
for c in (0x7F, 0x81, 0x8D, 0x8F, 0x90, 0x9D):
    if encs['WIN_ANSI'][c] is None: encs['WIN_ANSI'][c] = 'bullet'
for k, f in (('SYMBOL', 'Symbol'), ('ZAPF_DINGBATS', 'ZapfDingbats')):
    for c, n, _ in metrics[f][0]:
        if 0 <= c < 256: encs[k][c] = n

sorted_names = sorted(names, key=lambda s: s.encode())
idx = {n: i for i, n in enumerate(sorted_names)}
blob = ''.join(sorted_names)
assert len(sorted_names) < 0xFFFF

o = []
o.append('// @generated by a script from the Adobe Glyph List (BSD-3-Clause), the Adobe Core 14')
o.append('// AFM metrics and the encodings of ISO 32000-2 Annex D. Do not edit.\n')
o.append(f'pub static NAMES: &str = "{blob}";\n')
offs = [0]
for n in sorted_names: offs.append(offs[-1] + len(n))
def arr(name, ty, vals, per=16):
    o.append(f'pub static {name}: [{ty}; {len(vals)}] = [')
    for i in range(0, len(vals), per):
        o.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    o.append('];\n')
arr('OFFSETS', 'u32', offs)
arr('UNICODE', 'u16', [names[n] for n in sorted_names])
for k, v in encs.items():
    arr(k, 'u16', [idx[n] if n else 0xFFFF for n in v])
tables = {}
o.append('#[derive(Debug)]\npub struct Std14 {\n    pub name: &\'static str,\n    pub ascent: i16,\n    pub descent: i16,\n    pub bbox: [i16; 4],\n    /// (glyph name index, width) sorted by index; empty for monospaced fonts.\n    pub widths: &\'static [(u16, u16)],\n}\n')
for f in fonts:
    chars, info = metrics[f]
    ws = sorted({(idx[n], w) for _, n, w in chars})
    if all(w == 600 for _, w in ws): ws = []
    key = tuple(ws)
    if key not in tables:
        tname = 'W_' + re.sub(r'[^A-Z0-9]', '_', f.upper())
        tables[key] = tname
        o.append(f'static {tname}: [(u16, u16); {len(ws)}] = [')
        for i in range(0, len(ws), 8):
            o.append('    ' + ', '.join(f'({a}, {b})' for a, b in ws[i:i + 8]) + ',')
        o.append('];\n')
o.append(f'pub static STD14: [Std14; {len(fonts)}] = [')
for f in fonts:
    chars, info = metrics[f]
    ws = sorted({(idx[n], w) for _, n, w in chars})
    key = tuple([] if all(w == 600 for _, w in ws) else ws)
    asc, desc = info.get('Ascender', info['bbox'][3]), info.get('Descender', info['bbox'][1])
    o.append(f'    Std14 {{ name: "{f}", ascent: {asc}, descent: {desc}, bbox: {info["bbox"]}, widths: &{tables[key]} }},')
o.append('];')
open(out_path, 'w').write('\n'.join(o) + '\n')
print(len(sorted_names), 'names', len(blob), 'blob bytes', file=sys.stderr)
