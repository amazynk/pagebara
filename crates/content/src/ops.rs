//! The content stream operators of ISO 32000-2 Annex A.

/// An operator. Inline images (`BI … ID … EI`) arrive as one [`Op::InlineImage`].
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum Op {
    // General graphics state
    LineWidth,
    LineCap,
    LineJoin,
    MiterLimit,
    Dash,
    RenderingIntent,
    Flatness,
    ExtGState,
    // Special graphics state
    Save,
    Restore,
    Concat,
    // Path construction
    MoveTo,
    LineTo,
    CurveTo,
    CurveToV,
    CurveToY,
    ClosePath,
    Rect,
    // Path painting
    Stroke,
    CloseStroke,
    Fill,
    FillCompat,
    FillEvenOdd,
    FillStroke,
    FillStrokeEvenOdd,
    CloseFillStroke,
    CloseFillStrokeEvenOdd,
    EndPath,
    // Clipping
    Clip,
    ClipEvenOdd,
    // Text
    BeginText,
    EndText,
    CharSpacing,
    WordSpacing,
    HorizontalScale,
    Leading,
    Font,
    TextRender,
    TextRise,
    MoveText,
    MoveTextLeading,
    TextMatrix,
    NextLine,
    ShowText,
    ShowTextArray,
    NextLineShow,
    NextLineSpacingShow,
    // Type 3 fonts
    GlyphWidth,
    GlyphWidthBBox,
    // Colour
    StrokeSpace,
    FillSpace,
    StrokeColor,
    StrokeColorN,
    FillColor,
    FillColorN,
    StrokeGray,
    FillGray,
    StrokeRgb,
    FillRgb,
    StrokeCmyk,
    FillCmyk,
    // Shading, images, XObjects
    Shade,
    InlineImage,
    XObject,
    // Marked content
    MarkPoint,
    MarkPointProps,
    BeginMarked,
    BeginMarkedProps,
    EndMarked,
    // Compatibility
    BeginCompat,
    EndCompat,
    Unknown,
}

impl Op {
    pub fn from_keyword(k: &[u8]) -> Op {
        use Op::*;
        match k {
            b"w" => LineWidth,
            b"J" => LineCap,
            b"j" => LineJoin,
            b"M" => MiterLimit,
            b"d" => Dash,
            b"ri" => RenderingIntent,
            b"i" => Flatness,
            b"gs" => ExtGState,
            b"q" => Save,
            b"Q" => Restore,
            b"cm" => Concat,
            b"m" => MoveTo,
            b"l" => LineTo,
            b"c" => CurveTo,
            b"v" => CurveToV,
            b"y" => CurveToY,
            b"h" => ClosePath,
            b"re" => Rect,
            b"S" => Stroke,
            b"s" => CloseStroke,
            b"f" => Fill,
            b"F" => FillCompat,
            b"f*" => FillEvenOdd,
            b"B" => FillStroke,
            b"B*" => FillStrokeEvenOdd,
            b"b" => CloseFillStroke,
            b"b*" => CloseFillStrokeEvenOdd,
            b"n" => EndPath,
            b"W" => Clip,
            b"W*" => ClipEvenOdd,
            b"BT" => BeginText,
            b"ET" => EndText,
            b"Tc" => CharSpacing,
            b"Tw" => WordSpacing,
            b"Tz" => HorizontalScale,
            b"TL" => Leading,
            b"Tf" => Font,
            b"Tr" => TextRender,
            b"Ts" => TextRise,
            b"Td" => MoveText,
            b"TD" => MoveTextLeading,
            b"Tm" => TextMatrix,
            b"T*" => NextLine,
            b"Tj" => ShowText,
            b"TJ" => ShowTextArray,
            b"'" => NextLineShow,
            b"\"" => NextLineSpacingShow,
            b"d0" => GlyphWidth,
            b"d1" => GlyphWidthBBox,
            b"CS" => StrokeSpace,
            b"cs" => FillSpace,
            b"SC" => StrokeColor,
            b"SCN" => StrokeColorN,
            b"sc" => FillColor,
            b"scn" => FillColorN,
            b"G" => StrokeGray,
            b"g" => FillGray,
            b"RG" => StrokeRgb,
            b"rg" => FillRgb,
            b"K" => StrokeCmyk,
            b"k" => FillCmyk,
            b"sh" => Shade,
            b"BI" => InlineImage,
            b"Do" => XObject,
            b"MP" => MarkPoint,
            b"DP" => MarkPointProps,
            b"BMC" => BeginMarked,
            b"BDC" => BeginMarkedProps,
            b"EMC" => EndMarked,
            b"BX" => BeginCompat,
            b"EX" => EndCompat,
            _ => Unknown,
        }
    }

    pub const COUNT: usize = Op::Unknown as usize + 1;
}
