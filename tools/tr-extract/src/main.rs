//! Writes `po/pagebara.pot` from the translatable strings of the apps: `@tr(...)` in the
//! `.slint` files and `tr!`, `trn!` and `tr_noop!` in Rust code.
//!
//! ```text
//! cargo run -p tr-extract            # writes po/pagebara.pot
//! cargo run -p tr-extract -- --check # fails when po/pagebara.pot is out of date
//! ```
//!
//! A `// TRANSLATORS: ...` comment on the line before a string reaches the translators.
//! `po/update.sh` then merges the template into each language's catalog.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

mod scan;

const SLINT_DIRS: [&str; 2] = ["apps/desktop/ui", "apps/mobile/ui"];
const RUST_DIRS: [&str; 2] = ["apps", "crates"];

fn main() {
    let check = std::env::args().any(|a| a == "--check");
    // The checkout run from (Cargo runs the tool in the invoking directory); not the
    // compile-time path, which a target folder shared by several checkouts makes stale.
    let Some(root) = std::env::current_dir().ok().and_then(|d| {
        d.ancestors()
            .find(|a| a.join("po/pagebara.pot").exists() || a.join("po/update.sh").exists())
            .map(Path::to_path_buf)
    }) else {
        eprintln!("run tr-extract inside the pagebara checkout");
        std::process::exit(1);
    };
    let pot = template(&root);
    let path = root.join("po/pagebara.pot");
    if check {
        if std::fs::read_to_string(&path).ok().as_deref() != Some(pot.as_str()) {
            eprintln!("po/pagebara.pot is out of date: run `cargo run -p tr-extract`");
            std::process::exit(1);
        }
        return;
    }
    if let Err(e) = std::fs::write(&path, pot) {
        eprintln!("could not write {}: {e}", path.display());
        std::process::exit(1);
    }
}

/// The `.pot` file's text.
pub fn template(root: &Path) -> String {
    let mut files = Vec::new();
    for d in SLINT_DIRS {
        collect(&root.join(d), "slint", &mut files);
    }
    for d in RUST_DIRS {
        collect(&root.join(d), "rs", &mut files);
    }
    files.sort();
    let mut order: Vec<scan::Message> = Vec::new();
    let mut index: HashMap<(Option<String>, String), usize> = HashMap::new();
    for f in &files {
        let Ok(src) = std::fs::read_to_string(f) else {
            continue;
        };
        let rel = f
            .strip_prefix(root)
            .unwrap_or(f)
            .to_string_lossy()
            .replace('\\', "/");
        let found = if f.extension().is_some_and(|e| e == "slint") {
            scan::slint(&src)
        } else {
            scan::rust(&src)
        };
        for mut m in found {
            m.refs = vec![format!("{rel}:{}", m.line)];
            let key = (m.context.clone(), m.id.clone());
            match index.get(&key) {
                Some(&i) => {
                    let e = &mut order[i];
                    e.refs.append(&mut m.refs);
                    if e.plural.is_none() {
                        e.plural = m.plural;
                    }
                    for c in m.comments {
                        if !e.comments.contains(&c) {
                            e.comments.push(c);
                        }
                    }
                }
                None => {
                    index.insert(key, order.len());
                    order.push(m);
                }
            }
        }
    }
    let mut out = String::from(HEADER);
    for m in &order {
        out.push('\n');
        for c in &m.comments {
            out.push_str(&format!("#. {c}\n"));
        }
        out.push_str(&format!("#: {}\n", m.refs.join(" ")));
        if let Some(c) = &m.context {
            out.push_str(&format!("msgctxt {}\n", quote(c)));
        }
        out.push_str(&format!("msgid {}\n", quote(&m.id)));
        match &m.plural {
            Some(p) => {
                out.push_str(&format!("msgid_plural {}\n", quote(p)));
                out.push_str("msgstr[0] \"\"\nmsgstr[1] \"\"\n");
            }
            None => out.push_str("msgstr \"\"\n"),
        }
    }
    out
}

const HEADER: &str = r#"# Translatable strings of pagebara's desktop and mobile apps.
# Generated by tools/tr-extract; do not edit (run `cargo run -p tr-extract`).
msgid ""
msgstr ""
"Project-Id-Version: pagebara\n"
"MIME-Version: 1.0\n"
"Content-Type: text/plain; charset=UTF-8\n"
"Content-Transfer-Encoding: 8bit\n"
"Plural-Forms: nplurals=2; plural=(n != 1);\n"
"#;

fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn collect(dir: &Path, ext: &str, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    for e in rd.filter_map(Result::ok) {
        let p = e.path();
        let name = e.file_name();
        if p.is_dir() {
            if !matches!(
                name.to_str(),
                Some("target" | "tests" | "fuzz" | "android" | "ios")
            ) {
                collect(&p, ext, out);
            }
        } else if p.extension().is_some_and(|e| e == ext) && name != "tests.rs" {
            out.push(p);
        }
    }
}

#[cfg(test)]
mod tests {
    /// The committed template lists every string the code marks.
    #[test]
    fn template_is_current() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let committed = std::fs::read_to_string(root.join("po/pagebara.pot")).unwrap_or_default();
        assert!(
            committed == super::template(&root),
            "po/pagebara.pot is out of date: run `cargo run -p tr-extract`"
        );
    }
}
